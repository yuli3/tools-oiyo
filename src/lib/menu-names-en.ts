export function menuParts(menu: string, locale: string): { name: string; rest: string } {
  if (locale !== 'ko') {
    const en = MENU_EN[menu];
    if (en) return { name: en[0], rest: en[1] };
  }
  const [name, ...rest] = menu.split(' ');
  return { name, rest: rest.join(' ') };
}
